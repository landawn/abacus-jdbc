    @ParameterizedTest
    @ValueSource(booleans = { false, true })
    void mixedRunsExecuteWithinBatchSizeAndKeepInputOrder(final boolean insert) throws Exception {
        final JdbcDataSource source = source();
        try (Connection keeper = source.getConnection()) {
            createTable(keeper);
            final List<Row> rows = new ArrayList<>();
            for (int i = 1; i <= 11; i++) {
                rows.add(new Row(10_000 + i, "row-" + i));
            }
            rows.add(new Row(0, "generated"));
            rows.add(new Row(20_000, "last"));
            final TrackingRows input = new TrackingRows(rows);
            final TrackingSource tracking = new TrackingSource(source, input);
            final WriteDao dao = JdbcUtil.createDao(WriteDao.class, tracking);

            if (insert) {
                assertEquals(13, dao.batchInsert(input, 3).size());
                assertTrue(rows.get(11).getId() > 0);
            } else {
                dao.batchSave(input, 3);
                assertEquals(0, rows.get(11).getId());
            }

            assertEquals(3, tracking.firstExecutionProgress);
            assertEquals(List.of(3, 3, 3, 2, 1, 1), tracking.batchSizes);
            assertEquals(rows.stream().map(Row::getName).toList(), tracking.submittedNames);
            assertEquals(2, tracking.prepares, "The two SQL shapes should reuse their statements");
            assertTrue(tracking.idsUnchangedAtCommit);
            assertEquals(13, JdbcUtil.prepareQuery(keeper, "SELECT COUNT(*) FROM perf_row").queryForInt().get());
        }
    }

