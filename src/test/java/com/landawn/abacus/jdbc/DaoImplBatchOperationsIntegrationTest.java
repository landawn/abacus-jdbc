package com.landawn.abacus.jdbc;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.List;
import java.util.Map;
import java.util.stream.Stream;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.Arguments;
import org.junit.jupiter.params.provider.EnumSource;
import org.junit.jupiter.params.provider.MethodSource;
import org.junit.jupiter.params.provider.ValueSource;

import com.landawn.abacus.TestBase;
import com.landawn.abacus.annotation.Id;
import com.landawn.abacus.annotation.Table;
import com.landawn.abacus.jdbc.annotation.Query;
import com.landawn.abacus.jdbc.dao.CrudDao;
import com.landawn.abacus.query.Filters;

@Tag("integration")
public class DaoImplBatchOperationsIntegrationTest extends TestBase {

    private static final List<String> VALUE_COLUMNS = List.of("name", "score");
    private static final List<String> ALL_COLUMNS = List.of("id", "name", "score");
    private static final String INSERT_VALUES = "INSERT INTO batch_record(name, score) VALUES(:name, :score)";
    private static final String INSERT_ALL = "INSERT INTO batch_record(id, name, score) VALUES(:id, :name, :score)";
    private Connection keeper;
    private RecordDao dao;

    @BeforeEach
    void createDatabase() throws SQLException {
        final JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:dao_batch_operations_" + System.nanoTime());
        keeper = dataSource.getConnection();
        JdbcUtil.executeUpdate(keeper,
                "CREATE TABLE batch_record(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(40) UNIQUE, score INT CHECK (score <= 100))");
        dao = JdbcUtil.createDao(RecordDao.class, dataSource);
    }

    @AfterEach
    void closeDatabase() throws SQLException {
        if (keeper != null) {
            keeper.close();
        }
    }

    @ParameterizedTest(name = "{0}, explicitIds={1}, batchSize={2}")
    @MethodSource("batchModes")
    void batchInsertOrSave_overloadAndChunkSize_preserveRowsAndGeneratedKeys(final BatchOperation operation, final boolean explicitIds, final int batchSize)
            throws SQLException {
        final List<Record> records = records(explicitIds, false);
        final List<Long> ids = execute(operation, records, explicitIds, batchSize);

        assertEquals(3, rowCount());
        assertEquals(List.of("alpha", "beta", "gamma"), dao.list("name", Filters.expr("1 = 1 ORDER BY name")));
        if (operation.inserts()) {
            assertEquals(3, ids.size());
            assertTrue(ids.stream().allMatch(id -> id != null && id > 0));
            assertEquals(ids, records.stream().map(Record::getId).toList());
            for (int i = 0; i < ids.size(); i++) {
                assertEquals(records.get(i).getName(), dao.get(ids.get(i)).get().getName());
            }
        } else {
            assertEquals(List.of(), ids);
        }
        if (explicitIds) {
            assertEquals(List.of(10L, 11L, 12L), records.stream().map(Record::getId).toList());
        }
    }

    @ParameterizedTest
    @EnumSource(BatchOperation.class)
    void batchInsertOrSave_laterChunkFails_rollsBackEarlierChunks(final BatchOperation operation) throws SQLException {
        assertThrows(SQLException.class, () -> execute(operation, records(false, true), false, 1));
        assertEquals(0, rowCount(), "The first successful chunk must roll back with the failing second chunk");
        assertTrue(keeper.getAutoCommit());
    }

    @ParameterizedTest
    @EnumSource(BatchOperation.class)
    void batchInsertOrSave_emptyInputAndInvalidBatchSize_obeyValidationContract(final BatchOperation operation) throws SQLException {
        assertEquals(List.of(), execute(operation, List.of(), false, 1));
        assertThrows(IllegalArgumentException.class, () -> execute(operation, records(false, false), false, 0));
        assertEquals(0, rowCount());
    }

    @ParameterizedTest(name = "{0}, explicitId={1}")
    @MethodSource("singleModes")
    void insertOrSave_selectedColumnsAndSql_preserveEntityValues(final BatchOperation operation, final boolean explicitId) throws SQLException {
        final Record record = new Record(explicitId ? 20L : null, "single", 42);
        final List<String> columns = explicitId ? ALL_COLUMNS : VALUE_COLUMNS;
        final String sql = explicitId ? INSERT_ALL : INSERT_VALUES;
        Long id = null;
        switch (operation) {
            case SAVE_DEFAULT -> dao.save(record);
            case SAVE_COLUMNS -> dao.save(record, columns);
            case SAVE_SQL -> dao.save(sql, record);
            case INSERT_DEFAULT -> id = dao.insert(record);
            case INSERT_COLUMNS -> id = dao.insert(record, columns);
            case INSERT_SQL -> id = dao.insert(sql, record);
        }
        assertEquals(1, rowCount());
        assertEquals("single", dao.findOnlyOne(Filters.eq("score", 42)).get().getName());
        if (operation.inserts()) {
            assertEquals(record.getId(), id);
            assertTrue(id > 0);
        }
    }

    @ParameterizedTest
    @ValueSource(booleans = { false, true })
    void update_selectedProperties_appliesConditionAndPreservesOtherColumns(final boolean parameterizedCondition) throws SQLException {
        dao.batchSave(records(true, false), 10);
        final Record update = new Record(null, "ignored", 99);
        final int changed = dao.update(update, List.of("score"), parameterizedCondition ? Filters.eq("id", 11L) : Filters.expr("1 = 1"));

        assertEquals(parameterizedCondition ? 1 : 3, changed);
        assertEquals("beta", dao.get(11L).get().getName());
        assertEquals(99, dao.get(11L).get().getScore());
        assertEquals(parameterizedCondition ? 10 : 99, dao.get(10L).get().getScore());
        assertFalse(dao.exists(Filters.eq("name", "ignored")));
    }

    @ParameterizedTest(name = "{0}, large={1}, batchSize={2}")
    @MethodSource("annotatedUpdateModes")
    void annotatedBatchUpdate_bindingAndCountWidth_preserveRows(final UpdateBinding binding, final boolean large, final int batchSize) throws SQLException {
        dao.batchSave(records(true, false), 10);

        assertEquals(3L, annotatedUpdate(binding, large, false, batchSize));
        assertEquals(List.of(11, 21, 31), dao.list("score", Filters.expr("1 = 1 ORDER BY id")));
        assertEquals(0L, emptyAnnotatedUpdate(binding, large, batchSize));
    }

    @ParameterizedTest(name = "{0}, large={1}")
    @MethodSource("annotatedFailureModes")
    void annotatedBatchUpdate_laterChunkFails_rollsBackEarlierChanges(final UpdateBinding binding, final boolean large) throws SQLException {
        dao.batchSave(records(true, false), 10);
        dao.update(Map.of("score", 100), 11L);

        assertThrows(SQLException.class, () -> annotatedUpdate(binding, large, true, 1));
        assertEquals(List.of(10, 100, 30), dao.list("score", Filters.expr("1 = 1 ORDER BY id")));
    }

    @ParameterizedTest
    @ValueSource(booleans = { false, true })
    void batchUpdate_laterChunkFails_rollsBackDefaultAndSelectedColumns(final boolean selectedColumns) throws SQLException {
        dao.batchSave(records(true, false), 10);
        final List<Record> updates = List.of(new Record(10L, "changed", 11), new Record(11L, "invalid", 101));

        assertThrows(SQLException.class, () -> {
            if (selectedColumns) {
                dao.batchUpdate(updates, VALUE_COLUMNS, 1);
            } else {
                dao.batchUpdate(updates, 1);
            }
        });
        assertEquals(List.of("alpha", "beta", "gamma"), dao.list("name", Filters.expr("1 = 1 ORDER BY id")));
        assertEquals(List.of(10, 20, 30), dao.list("score", Filters.expr("1 = 1 ORDER BY id")));
    }

    @ParameterizedTest(name = "byId={0}, failure={1}")
    @MethodSource("deleteModes")
    void batchDelete_chunkedExecution_preservesAtomicity(final boolean byId, final boolean fail) throws SQLException {
        final List<Record> records = records(true, false);
        dao.batchSave(records, 10);
        JdbcUtil.executeUpdate(keeper, "CREATE TABLE batch_reference (record_id BIGINT REFERENCES batch_record(id))");
        if (fail) {
            JdbcUtil.executeUpdate(keeper, "INSERT INTO batch_reference VALUES (11)");
            assertThrows(SQLException.class, () -> {
                if (byId) {
                    dao.batchDeleteByIds(List.of(10L, 11L, 12L), 1);
                } else {
                    dao.batchDelete(records, 1);
                }
            });
            assertEquals(3, rowCount());
        } else {
            assertEquals(3, byId ? dao.batchDeleteByIds(List.of(10L, 11L, 12L), 1) : dao.batchDelete(records, 1));
            assertEquals(0, rowCount());
        }
    }

    private static Stream<Arguments> batchModes() {
        return Stream.of(BatchOperation.values())
                .flatMap(operation -> Stream.of(false, true)
                        .flatMap(explicitIds -> Stream.of(1, 8).map(batchSize -> Arguments.of(operation, explicitIds, batchSize))));
    }

    private static Stream<Arguments> singleModes() {
        return Stream.of(BatchOperation.values()).flatMap(operation -> Stream.of(false, true).map(explicitId -> Arguments.of(operation, explicitId)));
    }

    private static Stream<Arguments> annotatedUpdateModes() {
        return Stream.of(UpdateBinding.values())
                .flatMap(binding -> Stream.of(false, true).flatMap(large -> Stream.of(0, 1, 8).map(batchSize -> Arguments.of(binding, large, batchSize))));
    }

    private static Stream<Arguments> annotatedFailureModes() {
        return Stream.of(UpdateBinding.values()).flatMap(binding -> Stream.of(false, true).map(large -> Arguments.of(binding, large)));
    }

    private static Stream<Arguments> deleteModes() {
        return Stream.of(false, true).flatMap(byId -> Stream.of(false, true).map(fail -> Arguments.of(byId, fail)));
    }

    private long annotatedUpdate(final UpdateBinding binding, final boolean large, final boolean fail, final int batchSize) throws SQLException {
        final int secondScore = fail ? 101 : 21;
        return switch (binding) {
            case NAMED -> {
                final List<Record> parameters = List.of(new Record(10L, null, 11), new Record(11L, null, secondScore), new Record(12L, null, 31));
                yield large ? dao.updateNamedLarge(parameters, batchSize) : dao.updateNamed(parameters, batchSize);
            }
            case POSITIONAL -> {
                final List<List<?>> parameters = List.of(List.of(11, 10L), List.of(secondScore, 11L), List.of(31, 12L));
                yield large ? dao.updatePositionalLarge(parameters, batchSize) : dao.updatePositional(parameters, batchSize);
            }
            case SCALAR -> large ? dao.updateScalarLarge(List.of(10L, 11L, 12L), batchSize) : dao.updateScalar(List.of(10L, 11L, 12L), batchSize);
        };
    }

    private long emptyAnnotatedUpdate(final UpdateBinding binding, final boolean large, final int batchSize) throws SQLException {
        return switch (binding) {
            case NAMED -> large ? dao.updateNamedLarge(List.of(), batchSize) : dao.updateNamed(List.of(), batchSize);
            case POSITIONAL -> large ? dao.updatePositionalLarge(List.of(), batchSize) : dao.updatePositional(List.of(), batchSize);
            case SCALAR -> large ? dao.updateScalarLarge(List.of(), batchSize) : dao.updateScalar(List.of(), batchSize);
        };
    }

    private List<Long> execute(final BatchOperation operation, final List<Record> records, final boolean explicitIds, final int batchSize) throws SQLException {
        final List<String> columns = explicitIds ? ALL_COLUMNS : VALUE_COLUMNS;
        final String sql = explicitIds ? INSERT_ALL : INSERT_VALUES;
        return switch (operation) {
            case SAVE_DEFAULT -> {
                dao.batchSave(records, batchSize);
                yield List.of();
            }
            case SAVE_COLUMNS -> {
                dao.batchSave(records, columns, batchSize);
                yield List.of();
            }
            case SAVE_SQL -> {
                dao.batchSave(sql, records, batchSize);
                yield List.of();
            }
            case INSERT_DEFAULT -> dao.batchInsert(records, batchSize);
            case INSERT_COLUMNS -> dao.batchInsert(records, columns, batchSize);
            case INSERT_SQL -> dao.batchInsert(sql, records, batchSize);
        };
    }

    private int rowCount() throws SQLException {
        return JdbcUtil.prepareQuery(keeper, "SELECT COUNT(*) FROM batch_record").queryForInt().get();
    }

    private static List<Record> records(final boolean explicitIds, final boolean duplicateName) {
        return List.of(new Record(explicitIds ? 10L : null, "alpha", 10), new Record(explicitIds ? 11L : null, duplicateName ? "alpha" : "beta", 20),
                new Record(explicitIds ? 12L : null, "gamma", 30));
    }

    private enum BatchOperation {
        SAVE_DEFAULT, SAVE_COLUMNS, SAVE_SQL, INSERT_DEFAULT, INSERT_COLUMNS, INSERT_SQL;

        boolean inserts() {
            return name().startsWith("INSERT");
        }
    }

    private enum UpdateBinding {
        NAMED, POSITIONAL, SCALAR
    }

    public interface RecordDao extends CrudDao<Record, Long, RecordDao> {
        @Query(value = "UPDATE batch_record SET score = :score WHERE id = :id", batch = true)
        int updateNamed(List<Record> parameters, int batchSize) throws SQLException;

        @Query(value = "UPDATE batch_record SET score = :score WHERE id = :id", batch = true)
        long updateNamedLarge(List<Record> parameters, int batchSize) throws SQLException;

        @Query(value = "UPDATE batch_record SET score = ? WHERE id = ?", batch = true)
        int updatePositional(List<List<?>> parameters, int batchSize) throws SQLException;

        @Query(value = "UPDATE batch_record SET score = ? WHERE id = ?", batch = true)
        long updatePositionalLarge(List<List<?>> parameters, int batchSize) throws SQLException;

        @Query(value = "UPDATE batch_record SET score = score + 1 WHERE id = ?", batch = true, collectionAsSingleParameter = true)
        int updateScalar(List<Long> ids, int batchSize) throws SQLException;

        @Query(value = "UPDATE batch_record SET score = score + 1 WHERE id = ?", batch = true, collectionAsSingleParameter = true)
        long updateScalarLarge(List<Long> ids, int batchSize) throws SQLException;
    }

    @Table("batch_record")
    public static class Record {
        @Id
        private Long id;
        private String name;
        private int score;

        public Record() {
        }

        Record(final Long id, final String name, final int score) {
            this.id = id;
            this.name = name;
            this.score = score;
        }

        public Long getId() {
            return id;
        }

        public void setId(final Long id) {
            this.id = id;
        }

        public String getName() {
            return name;
        }

        public void setName(final String name) {
            this.name = name;
        }

        public int getScore() {
            return score;
        }

        public void setScore(final int score) {
            this.score = score;
        }
    }
}
