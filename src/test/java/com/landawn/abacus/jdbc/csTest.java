package com.landawn.abacus.jdbc;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.Arrays;
import java.util.stream.Stream;

import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import com.landawn.abacus.TestBase;

class csTest extends TestBase {

    @ParameterizedTest(name = "{0}")
    @MethodSource("constantNames")
    void constant_publicStringField_matchesItsName(final String name) throws ReflectiveOperationException {
        final Field field = cs.class.getDeclaredField(name);
        final int modifiers = field.getModifiers();

        assertEquals(String.class, field.getType());
        assertTrue(Modifier.isPublic(modifiers) && Modifier.isStatic(modifiers) && Modifier.isFinal(modifiers));
        assertEquals(name, field.get(null));
    }

    private static Stream<String> constantNames() {
        // Retain known names so removing a constant fails; include new public constants without repeating cases.
        final Stream<String> required = Stream.of("action", "afterInvokeAction", "autoGeneratedKeyExtractor", "batchParameters", "batchSize",
                "beforeInvokeAction", "closeHandler", "cmd", "columnGetter", "columnIndex", "columnName", "cond", "conn", "consumer", "consumerForAll", "count",
                "daoInterface", "defaultColumnGetter", "downstream", "ds", "entity", "entityClass", "executor", "filter", "func", "generatedKeyColumnIndexes",
                "generatedKeyColumnNames", "handler", "handlerClass", "id", "idExtractor", "isDefaultIdTester", "isolationLevel", "joinEntityPropName",
                "keyExtractor", "matchPropNames", "mergeFunction", "multimapSupplier", "n", "namedInsertSql", "namedSql", "offset", "orElseAction",
                "parameterNames", "parameters", "parametersSetter", "propNamesToInsert", "propNamesToRefresh", "propNamesToSave", "propNamesToUpdate",
                "propsToUpdate", "qualifier", "registrar", "resultExtractor", "resultExtractor1", "resultExtractor2", "resultExtractor3", "rowConsumer",
                "rowExtractor", "rowFilter", "rowMapper", "rowMapper1", "rowMapper2", "rowMapper3", "rs", "selectPropName", "sql", "sqlAction", "sqlAction1",
                "sqlAction2", "sqlAction3", "stmt", "stmtCreator", "stmtSetter", "supplier", "targetClass", "targetType", "targetValueType", "type", "url",
                "valueExtractor");
        final Stream<String> declared = Arrays.stream(cs.class.getDeclaredFields())
                .filter(field -> field.getType() == String.class && Modifier.isPublic(field.getModifiers()) && Modifier.isStatic(field.getModifiers())
                        && Modifier.isFinal(field.getModifiers()))
                .map(Field::getName);
        return Stream.concat(required, declared).distinct().sorted();
    }
}
