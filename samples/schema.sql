-- Each example gets a new in-memory H2 database. No existing tables are dropped.
CREATE TABLE user1 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(64) NOT NULL,
    last_name VARCHAR(64) NOT NULL,
    prop1 VARCHAR(64),
    email VARCHAR(128),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user2 (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(64) NOT NULL,
    last_name VARCHAR(64) NOT NULL,
    prop1 VARCHAR(64),
    email VARCHAR(128),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE device (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manufacture VARCHAR(64) NOT NULL,
    model VARCHAR(64) NOT NULL,
    user_id BIGINT REFERENCES user1(id) ON DELETE CASCADE
);

CREATE TABLE address (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street VARCHAR(64) NOT NULL,
    city VARCHAR(64) NOT NULL,
    user_id BIGINT REFERENCES user1(id) ON DELETE CASCADE
);

CREATE TABLE employee (
    employee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(64),
    last_name VARCHAR(64)
);

CREATE TABLE project (
    project_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(64),
    start_date TIMESTAMP
);

CREATE TABLE employee_project (
    employee_id INT NOT NULL REFERENCES employee(employee_id) ON DELETE CASCADE,
    project_id INT NOT NULL REFERENCES project(project_id) ON DELETE CASCADE,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (employee_id, project_id)
);
